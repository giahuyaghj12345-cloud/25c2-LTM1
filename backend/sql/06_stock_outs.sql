IF OBJECT_ID('dbo.stock_outs', 'U') IS NULL
CREATE TABLE dbo.stock_outs (
  id UNIQUEIDENTIFIER NOT NULL PRIMARY KEY DEFAULT NEWID(),
  number NVARCHAR(50) NOT NULL UNIQUE,
  date DATE NOT NULL,
  receiver NVARCHAR(200) NULL,
  reason NVARCHAR(255) NULL,
  status NVARCHAR(20) NOT NULL DEFAULT 'draft',
  createdBy NVARCHAR(100) NULL,
  createdAt DATETIME NOT NULL DEFAULT GETDATE(),
  updatedAt DATETIME NOT NULL DEFAULT GETDATE()
);

IF OBJECT_ID('dbo.stock_out_lines', 'U') IS NULL
CREATE TABLE dbo.stock_out_lines (
  id UNIQUEIDENTIFIER NOT NULL PRIMARY KEY DEFAULT NEWID(),
  stockOutId UNIQUEIDENTIFIER NOT NULL,
  materialId UNIQUEIDENTIFIER NULL,
  materialName NVARCHAR(200) NULL,
  quantity DECIMAL(18,2) NOT NULL DEFAULT 0,
  note NVARCHAR(255) NULL,
  CONSTRAINT FK_stock_out_lines_header FOREIGN KEY (stockOutId) REFERENCES dbo.stock_outs(id) ON DELETE CASCADE
);
